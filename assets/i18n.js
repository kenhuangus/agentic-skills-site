  function setLang(lang) {
    if (!dict[lang]) return;
    currentLang = lang;
    localStorage.setItem('ast_lang', lang);
    document.documentElement.lang = (lang === 'zh' ? 'zh-CN' : 'en');
    document.body.classList.toggle('is-zh', lang === 'zh');

    document.querySelectorAll('.lang__btn').forEach(btn => {
      btn.classList.toggle('is-on', btn.dataset.lang === lang);
    });

    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.dataset.i18n;
      if (dict[lang][key]) {
        if (el.hasAttribute('data-i18n-html')) {
          el.innerHTML = dict[lang][key];
        } else {
          el.textContent = dict[lang][key];
        }
      }
    });

    document.querySelectorAll('[data-i18n-aria]').forEach(el => {
      const key = el.dataset.i18nAria;
      if (dict[lang][key]) el.setAttribute('aria-label', dict[lang][key]);
    });

    document.querySelectorAll('.slide').forEach(s => {
      if (s.dataset.i18nTitle && dict[lang][s.dataset.i18nTitle]) {
        s.dataset.title = dict[lang][s.dataset.i18nTitle];
      }
    });

    document.dispatchEvent(new CustomEvent('ast:lang', { detail: { lang } }));
  }

